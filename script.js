// Static per-language URLs (generated by tools/build_i18n.py).
const languagePaths = { en: "/", de: "/de/", zh: "/zh/", zhTw: "/zh-tw/", ja: "/ja/" };

function getInitialLanguage() {
  // Legacy ?lang=xx links redirect to the static language URL.
  const params = new URLSearchParams(window.location.search);
  const fromQuery = params.get("lang");
  const isHome = window.location.pathname === "/" || window.location.pathname === "/index.html";
  if (isHome && fromQuery && fromQuery !== "en" && languagePaths[fromQuery]) {
    window.location.replace(languagePaths[fromQuery] + window.location.hash);
  }
  // Each generated page declares its own language.
  const pageLang = document.documentElement.dataset.pageLang;
  return translations[pageLang] ? pageLang : "en";
}

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = languageMeta[language] || "en";
  document.title = dictionary.documentTitle;

  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", dictionary.metaDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) element.setAttribute("aria-label", dictionary[key]);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    if (isActive) button.setAttribute("aria-current", "page");
    else button.removeAttribute("aria-current");
  });

  updateFooterDate(dictionary, language);
}

function getLastUpdatedDate(language, element) {
  const source = element.getAttribute("datetime") || document.lastModified;
  const modified = new Date(source);
  if (Number.isNaN(modified.getTime())) return "";

  return new Intl.DateTimeFormat(languageMeta[language] || "en", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit"
  }).format(modified);
}

function updateFooterDate(dictionary, language) {
  document.querySelectorAll("[data-updated]").forEach((element) => {
    const date = getLastUpdatedDate(language, element);
    element.textContent = date ? `${dictionary.footerUpdated} ${date}` : dictionary.footerUpdated;
  });
}

document.querySelectorAll("[data-lang]").forEach((link) => {
  link.addEventListener("click", () => {
    try { localStorage.setItem("preferredLanguage", link.dataset.lang); } catch (e) {}
  });
});

